function png(){
 const chunk=(type,data)=>{const b=Buffer.alloc(data.length+12);b.writeUInt32BE(data.length);b.write(type,4);data.copy(b,8);let crc=0xffffffff;for(const byte of b.subarray(4,-4)){crc^=byte;for(let i=0;i<8;i++)crc=(crc&1)?0xedb88320^(crc>>>1):crc>>>1;}b.writeUInt32BE((crc^0xffffffff)>>>0,b.length-4);return b;};
 const header=Buffer.alloc(13);header.writeUInt32BE(64);header.writeUInt32BE(32,4);header[8]=8;header[9]=6;
 return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',header),chunk('IDAT',deflateSync(Buffer.alloc(257*32))),chunk('IEND',Buffer.alloc(0))]).toString('base64');
}
test('code-only capes: private lockers, one claimant, retry, revocation and publication lifecycle',async t=>{
 const directory=mkdtempSync(join(tmpdir(),'bloom-redeem-'));
 const store=new SqliteCosmeticsStore({directory,publicUrl:'https://fixture.invalid'});
 const secondStore=new SqliteCosmeticsStore({directory,publicUrl:'https://fixture.invalid'});
 const owner='a'.repeat(32),one='b'.repeat(32),two='c'.repeat(32),stranger='d'.repeat(32);
 const authorize=async req=>{if(req.headers.authorization!=='Bearer owner')throw Object.assign(new Error('Unauthorized'),{status:401});};
 const admin=createCapeAdmin({authorize,store,ownerUuid:owner});
 const makePublic=s=>createCosmeticsApi({store:s,owners:[owner],verify:async token=>{if(![one,two,stranger].includes(token))throw Object.assign(new Error('Bad session'),{status:401});return token;}});
 const publicApis=[makePublic(store),makePublic(secondStore)];let index=0;
 const server=http.createServer(async(req,res)=>{const url=new URL(req.url,'http://localhost');if(await admin.handle(req,res,url.pathname))return;if(await publicApis[index++%2].handle(req,res,url.pathname,url))return;res.writeHead(404).end();});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 t.after(()=>{server.close();store.close();secondStore.close();rmSync(directory,{recursive:true,force:true});});
 const call=async(path,method='GET',body,token)=>{const r=await fetch(`http://127.0.0.1:${server.address().port}${path}`,{method,headers:{'content-type':'application/json',...(token?{authorization:'Bearer '+token}:{})},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,data:await r.json()};};
 const prefix='/v1/owner/content/capes',input={name:'Private Sakura',texture:png(),requiresCode:true};
 const publish=body=>call(prefix+'/publish','POST',body,'owner');
 let result=await publish(input);assert.equal(result.status,201);const id=result.data.id;let revision=result.data.revision;
 const codes=prefix+'/'+id+'/codes';
 const generate=async()=>{const r=await call(codes,'POST',{expectedRevision:revision},'owner');assert.equal(r.status,201);return r.data;};
 const redeem=(code,player)=>call('/v1/capes/redeem','POST',{code,uuid:owner},player);
 const locker=async player=>(await call('/v1/capes/locker','GET',undefined,player)).data.items;
 assert.equal((await call('/v1/capes')).data.items.length,0);
 assert.equal((await locker(one)).length,0);
 assert.equal((await call('/v1/capes/locker')).status,401);
 assert.equal((await call(codes,'POST',{expectedRevision:revision})).status,401);
 assert.equal((await call('/v1/capes/equipped','PUT',{capeId:id},one)).status,404);
 assert.equal((await call('/v1/capes/'+id+'/texture')).status,401);
 assert.equal((await call('/v1/capes/'+id+'/texture','GET',undefined,one)).status,404);
 const first=await generate(),second=await generate();
 assert.equal((await call(codes,'GET',undefined,'owner')).data.items.length,2);
 assert.ok(!JSON.stringify((await call(codes,'GET',undefined,'owner')).data).includes(first.code));
 assert.ok(!JSON.stringify(store.db.prepare('SELECT * FROM cape_codes').all()).includes(first.code));
 const contenders=await Promise.all([redeem(first.code.toLowerCase().replaceAll('-',' '),one),redeem(first.code,two)]);
 assert.deepEqual(contenders.map(r=>r.status).sort(),[200,409]);
 const winner=contenders[0].status===200?one:two,loser=winner===one?two:one;
 assert.equal((await redeem(first.code,winner)).data.alreadyClaimed,true);
 assert.equal((await redeem(first.code,loser)).data.error,'code_already_used');
 assert.equal((await locker(winner))[0].id,id);assert.equal((await locker(loser)).length,0);
 assert.equal((await redeem(second.code,winner)).data.error,'cape_already_claimed');
 assert.equal((await redeem(second.code,loser)).status,200);
 assert.equal((await call('/v1/capes/equipped','PUT',{capeId:id},winner)).status,200);
 // A previous public wearer without a claim must not acquire code-only access.
 store.db.prepare('INSERT INTO players(uuid,cape_id) VALUES(?,?)').run(stranger,id);
 const equipped=(await call('/v1/capes/equipped?uuids='+[winner,stranger].join(','))).data.items;
 assert.equal(equipped[0].capeId,id);assert.equal(equipped[1].capeId,null);
 assert.equal((await call('/v1/capes/'+id+'/texture','GET',undefined,winner)).status,200);
 assert.equal((await call('/v1/capes/equipped','PUT',{capeId:id},stranger)).status,404);
 const revoked=await generate();assert.equal((await call(codes+'/'+revoked.id+'/revoke','POST',{expectedRevision:revision},'owner')).status,200);
 assert.equal((await redeem(revoked.code,stranger)).data.error,'code_unavailable');
 assert.equal((await call(codes+'/'+first.id+'/revoke','POST',{expectedRevision:revision},'owner')).status,409);
 assert.equal((await call(prefix+'/'+id+'/remove','POST',{expectedRevision:revision},'owner')).status,200);
 assert.equal((await locker(winner)).length,0);
 assert.equal((await call(prefix+'/'+id+'/restore','POST',{expectedRevision:revision},'owner')).status,200);
 assert.equal((await locker(winner))[0].id,id);
 result=await publish({...input,name:'Updated Sakura',capeId:id,expectedRevision:revision});revision=result.data.revision;
 assert.equal((await locker(winner))[0].name,'Updated Sakura');
 result=await publish({...input,requiresCode:false,capeId:id,expectedRevision:revision});revision=result.data.revision;
 const publicCape=(await call('/v1/capes')).data.items[0];assert.equal(publicCape.id,id);
 const publicLease=publicCape.textureUrl.split('/').pop();await store.leasedAsset(publicLease);
 result=await publish({...input,capeId:id,expectedRevision:revision});revision=result.data.revision;
 await assert.rejects(store.leasedAsset(publicLease));
 assert.equal((await call('/v1/capes')).data.items.length,0);assert.equal((await locker(winner))[0].id,id);
 const thirdConnection=new SqliteCosmeticsStore({directory,publicUrl:'https://fixture.invalid'});
 try{assert.equal((await thirdConnection.catalog(winner))[0].id,id);assert.equal(thirdConnection.redeemCode(winner,first.code).alreadyClaimed,true);}finally{thirdConnection.close();}
});
